#!/usr/bin/env python3
"""Benchmark the minimum-cost-flow solver on synthetic residue-carrying scenes.

The work a flow solve does is set by the number of residues, not by the number
of pixels, so a sweep over sizes says more than a single point.  Every scene is
generated deterministically in memory; nothing is read from disk and no
external solver is required.
"""

import argparse
import json
import statistics
import time
from pathlib import Path

import numpy as np

from parvaneh import make_synthetic, network_flow_unwrap, phase_residues, rmse_aligned
from parvaneh.synthetic import wrap_phase


def timed(function, repeat):
    """Run ``function`` ``repeat`` times and return its last result, samples."""
    samples = []
    result = None
    for _ in range(repeat):
        start = time.perf_counter()
        result = function()
        samples.append(time.perf_counter() - start)
    return result, samples


def measure(size, noise, seed, cost, repeat):
    """Time one square scene and collect the solver's own work counters."""
    truth, phase, weight = make_synthetic((size, size), noise=noise, seed=seed)
    charge = int(np.abs(phase_residues(phase)).sum())
    result, samples = timed(
        lambda: network_flow_unwrap(phase, weight, cost=cost,
                                    return_info=True), repeat)
    unwrapped, info = result
    # Unwrapping only adds whole turns, so the output must still live in the
    # same period as the input.  A nonzero value here would be a real bug.
    departure = float(np.abs(wrap_phase(unwrapped) - phase).max())
    return {
        "shape_rows_cols": [size, size],
        "input_absolute_charge": charge,
        "nodes": info.nodes,
        "edges": info.edges,
        "augmentations": info.augmentations,
        "max_jump": info.max_jump,
        "median_seconds": statistics.median(samples),
        "samples_seconds": samples,
        "aligned_rmse_rad": rmse_aligned(unwrapped, truth),
        "max_wrapped_departure_rad": departure,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", nargs="+", type=int, default=[32, 48, 64],
                        help="square scene sizes to sweep (default: 32 48 64)")
    parser.add_argument("--noise", type=float, default=1.0,
                        help="generator noise scale; 1.0 gives noisy scenes "
                             "with hundreds of units of residue charge, which "
                             "is what the flow solver actually has to work on")
    parser.add_argument("--seed", type=int, default=11)
    parser.add_argument("--cost", choices=("linear", "quadratic"),
                        default="linear")
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--report", type=Path,
                        default=Path("reports/mcf_benchmark.json"))
    args = parser.parse_args()
    if any(size < 2 for size in args.sizes) or args.repeat < 1 or args.noise < 0:
        parser.error("sizes must be >= 2, repeat >= 1, and noise nonnegative")

    records = []
    for size in args.sizes:
        record = measure(size, args.noise, args.seed, args.cost, args.repeat)
        records.append(record)
        print("{0:>4} x {1:<4} charge {2:>5}  nodes {3:>6}  augmentations "
              "{4:>5}  median {5:.4f} s  RMSE {6:.4f} rad".format(
                  size, size, record["input_absolute_charge"], record["nodes"],
                  record["augmentations"], record["median_seconds"],
                  record["aligned_rmse_rad"]))

    document = {
        "schema_version": 1,
        "input": "generated by parvaneh.make_synthetic",
        "noise": args.noise,
        "seed": args.seed,
        "cost": args.cost,
        "measured_runs": args.repeat,
        "results": records,
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(document, indent=2) + "\n")
    print("wrote {}".format(args.report))


if __name__ == "__main__":
    main()
