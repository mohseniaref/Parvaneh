#!/usr/bin/env python3
"""Benchmark readable and Numba quality-guided implementations synthetically."""

import argparse
import json
import statistics
import time
from pathlib import Path

from accelerated_unwrap import make_synthetic, quality_guided_unwrap, rmse_aligned


def timed(function, repeat):
    samples = []
    result = None
    for _ in range(repeat):
        start = time.perf_counter()
        result = function()
        samples.append(time.perf_counter() - start)
    return result, samples


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rows", type=int, default=257)
    parser.add_argument("--cols", type=int, default=257)
    parser.add_argument("--noise", type=float, default=0.08)
    parser.add_argument("--seed", type=int, default=17)
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--report", type=Path,
                        default=Path("reports/path_benchmark.json"))
    args = parser.parse_args()
    if args.rows < 2 or args.cols < 2 or args.repeat < 1 or args.noise < 0:
        parser.error("rows/cols must be >=2, repeat >=1, and noise nonnegative")

    truth, phase, _ = make_synthetic(
        (args.rows, args.cols), noise=args.noise, seed=args.seed)
    # Compile Numba and warm both implementations outside the measured region.
    quality_guided_unwrap(phase, "min_gradient", backend="numba")
    quality_guided_unwrap(phase, "min_gradient", backend="python")

    records = []
    for backend in ("python", "numba"):
        result, samples = timed(lambda selected=backend: quality_guided_unwrap(
            phase, "min_gradient", backend=selected), args.repeat)
        record = {
            "implementation": backend,
            "scope": "in-process compute",
            "samples_seconds": samples,
            "median_seconds": statistics.median(samples),
            "aligned_rmse_rad": rmse_aligned(result, truth),
        }
        records.append(record)
        print("{:<8} median {:.6f} s; RMSE {:.5f} rad".format(
            backend, record["median_seconds"], record["aligned_rmse_rad"]))

    document = {
        "schema_version": 2,
        "input": "generated by accelerated_unwrap.make_synthetic",
        "shape_rows_cols": [args.rows, args.cols],
        "noise": args.noise,
        "seed": args.seed,
        "warmup_runs": 1,
        "measured_runs": args.repeat,
        "results": records,
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(document, indent=2) + "\n")
    print("wrote {}".format(args.report))


if __name__ == "__main__":
    main()

